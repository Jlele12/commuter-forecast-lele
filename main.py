#!/usr/bin/env python3
"""Entry for Charm the Commuter: Forecast for a City (u-golden-heron-44-charm-the-commuter-forecast-a-city-4018259e).

Writes one line (max 200 characters) for the judge to /output/entry.txt:
the brief's ask, landed in a single read, grounded and specific. No network,
no randomness: every run writes the same text so both graded runs match
byte for byte.
"""
from pathlib import Path

LINE = "Commuter forecast for Delaygrad: light drizzle of resignation, scattered apologizing, evening fog of maybe leaving on time."


def main() -> None:
    out = Path("/output")
    out.mkdir(parents=True, exist_ok=True)
    text = LINE.strip()
    assert 1 <= len(text) <= 200, "entry must be 1-200 characters"
    entry_path = out / "entry.txt"
    entry_path.write_text(text, encoding="utf-8")
    print(text, f"({len(text)} chars)")


if __name__ == "__main__":
    main()
